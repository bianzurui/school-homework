#include <stdio.h>

int main()
{
    int k, x, i, j, m, t, len, width;
    char s[10];          /* 保存输入的数字（字符串形式） */
    int b[7][5];         /* 当前这一位数字的点阵 */
    char pic[7][40];     /* 整个输出图形 */

    scanf("%d", &k);

    for (x = 0; x < k; x++) {
        scanf("%s", s);

        /* 数一数有几位数字 */
        len = 0;
        while (s[len] != '\0') {
            len++;
        }

        /* 先把整张图填成空格 */
        for (i = 0; i < 7; i++) {
            for (j = 0; j < 40; j++) {
                pic[i][j] = ' ';
            }
        }

        /* 一位一位地画，每位数字占 7 列（5 列字形 + 2 个空格） */
        for (j = 0; j < len; j++) {
            t = s[j] - '0';

            /* 每位数字开始前清空 b */
            for (i = 0; i < 7; i++) {
                for (m = 0; m < 5; m++) {
                    b[i][m] = 0;
                }
            }

            /* 上、中、下三条横线：2、3、5、6、8、9 都有 */
            if (t == 2 || t == 3 || t == 5 || t == 6 || t == 8 || t == 9) {
                for (m = 0; m < 5; m++) {
                    b[0][m] = 1;
                    b[3][m] = 1;
                    b[6][m] = 1;
                }
            }

            /* 0：上、下横线 + 左右两列 */
            if (t == 0) {
                for (m = 0; m < 5; m++) {
                    b[0][m] = 1;
                    b[6][m] = 1;
                }
                for (i = 0; i < 7; i++) {
                    b[i][0] = 1;
                    b[i][4] = 1;
                }
            }

            /* 1：右侧一列 */
            if (t == 1) {
                for (i = 0; i < 7; i++) {
                    b[i][4] = 1;
                }
            }

            /* 2 */
            if (t == 2) {
                b[1][4] = 1;
                b[2][4] = 1;
                b[4][0] = 1;
                b[5][0] = 1;
            }

            /* 3 */
            if (t == 3) {
                b[1][4] = 1;
                b[2][4] = 1;
                b[4][4] = 1;
                b[5][4] = 1;
            }

            /* 4：中横线 + 右侧一列 + 左上角 */
            if (t == 4) {
                for (m = 0; m < 5; m++) {
                    b[3][m] = 1;
                }
                for (i = 0; i < 7; i++) {
                    b[i][4] = 1;
                }
                b[0][0] = 1;
                b[1][0] = 1;
                b[2][0] = 1;
            }

            /* 5 */
            if (t == 5) {
                b[1][0] = 1;
                b[2][0] = 1;
                b[4][4] = 1;
                b[5][4] = 1;
            }

            /* 6：左侧一列 + 右下部分 */
            if (t == 6) {
                for (i = 0; i < 7; i++) {
                    b[i][0] = 1;
                }
                b[4][4] = 1;
                b[5][4] = 1;
            }

            /* 7：上横线 + 右侧一列 */
            if (t == 7) {
                for (m = 0; m < 5; m++) {
                    b[0][m] = 1;
                }
                for (i = 0; i < 7; i++) {
                    b[i][4] = 1;
                }
            }

            /* 8：左右两列 */
            if (t == 8) {
                for (i = 0; i < 7; i++) {
                    b[i][0] = 1;
                    b[i][4] = 1;
                }
            }

            /* 9：右侧一列 + 左上部分 */
            if (t == 9) {
                for (i = 0; i < 7; i++) {
                    b[i][4] = 1;
                }
                b[1][0] = 1;
                b[2][0] = 1;
            }

            /* 把这一位的点阵复制到 pic 中，从第 j*7 列开始 */
            for (i = 0; i < 7; i++) {
                for (m = 0; m < 5; m++) {
                    if (b[i][m] == 1) {
                        pic[i][j * 7 + m] = '*';
                    }
                }
            }
        }

        /* 最后一位数字后面不输出空格 */
        width = len * 7 - 2;

        /* 第一行输出 x 和冒号 */
        printf("%s:\n", s);

        /* 之后输出 7 行图形 */
        for (i = 0; i < 7; i++) {
            for (j = 0; j < width; j++) {
                printf("%c", pic[i][j]);
            }
            printf("\n");
        }
    }

    return 0;
}